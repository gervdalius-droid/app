#!/usr/bin/env python3
"""Builds surinkimas/index.html (the assembly bench page) from shopflow-app/index.html:
the same boot guard and scripts (from ../shopflow-app/), minus what is not for the bench
(the cabinet-builder handoff, notices, dev data), plus kiosk.js, which replaces ShopFlow's
screens with the one assembly screen. Run after any change to ShopFlow's script list."""
import re, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = open(os.path.join(ROOT, 'shopflow-app/index.html'), encoding='utf-8').read()
head, body = src.split('<body>', 1)
ver = re.search(r'name="shopflow-build" content="([^"]+)"', head).group(1)
guard = re.search(r'(  <!-- =+\s*\n\s*Boot guard.*?</script>\n)', body, re.S).group(1).replace('ShopFlow neįsijungė', 'Surinkimas neįsijungė').replace('ShopFlow did not start', 'Assembly did not start')
skip = ('realdata.js', 'builder-link.js', 'notices.js', 'workshop-auth.js', 'swood.js', 'sheet-export.js', 'gpm.js', 'wb.js')
scripts = []
for m in re.finditer(r'  <script src="([^"]+)"([^>]*)></script>', body):
    s, rest = m.group(1), m.group(2)
    if any(k in s for k in skip): continue
    if not s.startswith('../'): s = '../shopflow-app/' + s
    scripts.append('  <script src="%s"%s></script>' % (s, rest))
    if 'assembly.js' in s: scripts.append('  <script src="../shopflow-app/kiosk.js?v=%s"></script>' % ver)
out = '''<!DOCTYPE html>
<html lang="lt">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1.0, viewport-fit=cover">
<meta name="robots" content="noindex,nofollow">
<title>Surinkimas · Dėdės Baldai</title>
<!-- The assembly bench tablet: sign in with name + PIN, scan a panel, its cabinet's drawing and 3-D view open.
     Generated by tools/make-surinkimas.py from shopflow-app/index.html — edit that script, not this file. -->
<link rel="icon" type="image/png" href="../shopflow-app/icons/favicon-64.png">
<meta name="theme-color" content="#0071e3">
<link rel="stylesheet" href="../shopflow-app/styles.css?v=%s">
  <meta name="shopflow-build" content="%s">
</head>
<body>
%s  <div id="app"></div>
  <div id="modal-root"></div>
  <div id="drawer-root"></div>
  <div id="toast-root"></div>
  <div id="palette-root"></div>
  <div id="mywork-root"></div>
%s
  <script>App.boot().catch(function (e) { console.error('[boot]', e); document.body.innerHTML = '<p style="font:15px system-ui;padding:40px">Surinkimas neįsijungė: ' + (e && e.message || e) + '</p>'; })</script>
</body>
</html>
''' % (ver, ver, guard, '\n'.join(scripts))
open(os.path.join(ROOT, 'surinkimas/index.html'), 'w', encoding='utf-8').write(out)
print('surinkimas/index.html', ver, len(scripts), 'scripts')
