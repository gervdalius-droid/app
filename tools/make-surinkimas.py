#!/usr/bin/env python3
"""Builds surinkimas/index.html (the assembly bench page) from shopflow-app/index.html:
the same boot guard and scripts (from ../shopflow-app/), minus what is not for the bench
(the cabinet-builder handoff, notices, dev data), plus kiosk.js, which replaces ShopFlow's
screens with the one assembly screen. Run after any change to ShopFlow's script list."""
import re, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = open(os.path.join(ROOT, 'shopflow-app/index.html'), encoding='utf-8').read()
head, body = src.split('<body>', 1)
ver = re.search(r'name="shopflow-build" content="([^"]+)"', head).group(1)
guard = re.search(r'(  <!-- =+\s*\n\s*Boot guard.*?</script>\n)', body, re.S).group(1).replace('ShopFlow neįsijungė', 'Surinkimas neįsijungė').replace('ShopFlow did not start', 'Assembly did not start')
skip = ('realdata.js', 'builder-link.js', 'notices.js', 'workshop-auth.js', 'swood.js', 'sheet-export.js', 'gpm.js', 'wb.js')
scripts = []
for m in re.finditer(r'  <script src="([^"]+)"([^>]*)></script>', body):
    s, rest = m.group(1), m.group(2)
    if any(k in s for k in skip): continue
    if not s.startswith('../'): s = '../shopflow-app/' + s
    scripts.append('  <script src="%s"%s></script>' % (s, rest))
    if 'assembly.js' in s: scripts.append('  <script src="../shopflow-app/kiosk.js?v=%s"></script>' % ver)
out = '''<!DOCTYPE html>
<html lang="lt">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1.0, viewport-fit=cover">
<meta name="robots" content="noindex,nofollow">
<title>Surinkimas · Dėdės Baldai</title>
<!-- The assembly bench tablet: sign in with name + PIN, scan a panel, its cabinet's drawing and 3-D view open.
     Generated by tools/make-surinkimas.py from shopflow-app/index.html — edit that script, not this file. -->
<link rel="icon" type="image/png" href="icons/favicon-64.png">
<link rel="manifest" href="manifest.json">
<meta name="theme-color" content="#c46218">
<link rel="apple-touch-icon" href="icons/apple-touch-icon.png">
<meta name="mobile-web-app-capable" content="yes">
<meta name="apple-mobile-web-app-capable" content="yes">
<meta name="apple-mobile-web-app-title" content="Surinkimas">
<link rel="stylesheet" href="../shopflow-app/styles.css?v=%s">
  <meta name="shopflow-build" content="%s">
</head>
<body>
%s  <div id="app"></div>
  <div id="modal-root"></div>
  <div id="drawer-root"></div>
  <div id="toast-root"></div>
  <div id="palette-root"></div>
  <div id="mywork-root"></div>
%s
  <script>if ("serviceWorker" in navigator) navigator.serviceWorker.register("sw.js").catch(function () {});</script>
  <script>App.boot().catch(function (e) { console.error('[boot]', e); document.body.innerHTML = '<p style="font:15px system-ui;padding:40px">Surinkimas neįsijungė: ' + (e && e.message || e) + '</p>'; })</script>
</body>
</html>
''' % (ver, ver, guard, '\n'.join(scripts))
open(os.path.join(ROOT, 'surinkimas/index.html'), 'w', encoding='utf-8').write(out)
# installed on the tablet as an app of its own (no address bar): the manifest, and a service worker (ShopFlow's
# App.boot registers "sw.js" next to the page when the page has a manifest) — network first, the last copy offline
import json
manifest = {"name": "Surinkimas · Dėdės Baldai", "short_name": "Surinkimas", "id": "/surinkimas/", "start_url": "/surinkimas/", "scope": "/surinkimas/",
            "display": "standalone", "display_override": ["standalone"], "orientation": "any", "background_color": "#f5f5f7", "theme_color": "#c46218", "lang": "lt",
            "description": "Surinkimo stalas: nuskenuokite detalę — atsidaro spintelės brėžinys ir 3D vaizdas",
            "icons": [{"src": "icons/icon-192.png", "sizes": "192x192", "type": "image/png", "purpose": "any"},
                      {"src": "icons/icon-512.png", "sizes": "512x512", "type": "image/png", "purpose": "any"},
                      {"src": "icons/maskable-512.png", "sizes": "512x512", "type": "image/png", "purpose": "maskable"}]}
open(os.path.join(ROOT, 'surinkimas/manifest.json'), 'w', encoding='utf-8').write(json.dumps(manifest, ensure_ascii=False, indent=1) + '\n')
shell = ['./', 'index.html', 'manifest.json', 'icons/icon-192.png'] + [re.search(r'src="([^"]+)"', x).group(1) for x in scripts] + ['../shopflow-app/styles.css?v=' + ver]
sw = """/* Surinkimas — the assembly bench app's service worker (generated by tools/make-surinkimas.py).
   Network first: the bench always gets the latest; with no network it opens from the last copy. */
var BUILD = "%s", CACHE = "surinkimas-" + BUILD;
var SHELL = %s;
self.addEventListener("install", function (e) {
  e.waitUntil(caches.open(CACHE).then(function (c) { return Promise.all(SHELL.map(function (u) { return c.add(new Request(u, { cache: "reload" })).catch(function () {}); })); }));
});
self.addEventListener("activate", function (e) {
  e.waitUntil(caches.keys().then(function (ks) { return Promise.all(ks.filter(function (k) { return k.indexOf("surinkimas-") === 0 && k !== CACHE; }).map(function (k) { return caches.delete(k); })); }));
});
self.addEventListener("fetch", function (e) {
  var r = e.request, u = new URL(r.url);
  if (r.method !== "GET" || u.origin !== location.origin || u.pathname.indexOf("/builder/") === 0) return;   // the cloud and the 3-D page: straight to the network
  e.respondWith(fetch(r).then(function (res) {
    if (res && res.ok && res.type === "basic") { var cp = res.clone(); caches.open(CACHE).then(function (c) { c.put(r, cp); }); }
    return res;
  }).catch(function () { return caches.match(r, { ignoreSearch: r.mode === "navigate" }).then(function (m) { return m || caches.match("index.html"); }); }));
});
""" % (ver, json.dumps(shell))
open(os.path.join(ROOT, 'surinkimas/sw.js'), 'w', encoding='utf-8').write(sw)
print('surinkimas/index.html', ver, len(scripts), 'scripts')
